// Android output for the stock brand: the OtherSync family mark.
//
// The adaptive icon is the mark split into its two layers: the night tile's
// radial gradient full-bleed in the background, and the ring, glow, sync
// glyph and centre point in the foreground. The geometry is brandmark's own
// (GeometryFor), drawn in the 512-unit design space inside one <group> that
// scales it into the 108dp canvas, so the phone icon and the desktop icon are
// the same numbers.
package main

import (
	"bytes"
	"fmt"
	"image/color"
	"math"
	"path/filepath"

	"github.com/otherworld/nimbo/internal/brandmark"
)

// The sheet's night gradient (brandmark keeps its own copy unexported).
var (
	nightCentre = color.RGBA{0x12, 0x20, 0x2B, 0xff}
	nightEdge   = color.RGBA{0x0A, 0x0F, 0x16, 0xff}
)

// ringSafeFill is how much of the 66dp safe zone the ring's outer edge spans.
// The master's ring spans 376 of the 512 tile (73%); 80% of the safe zone is
// 52.8dp, which is 73% of the 72dp a launcher shows, so the phone icon keeps
// the desktop tile's proportions.
const ringSafeFill = 0.80

// markScale is dp per design unit for the launcher layers.
func markScale(g brandmark.Geometry) float64 {
	return ringSafeFill * adaptiveSafe / 2 / (g.RingR + g.RingW/2)
}

// writeAndroidMark writes the stock adaptive-icon layers and the notification
// small icon into res/drawable.
func writeAndroidMark(dir, name string) {
	writeFile(filepath.Join(dir, name+"_background.xml"), markBackgroundVector())
	writeFile(filepath.Join(dir, name+"_foreground.xml"), markForegroundVector(false))
	writeFile(filepath.Join(dir, name+"_monochrome.xml"), markForegroundVector(true))
	writeFile(filepath.Join(dir, "ic_notification.xml"), notificationVector())
}

const markHeader = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by shell/windows/appicon — do not edit by hand.
     Regenerate: cd shell/windows/appicon && go run . android
     %s -->
`

// markBackgroundVector is the night tile's radial gradient, full-bleed: the
// launcher applies its own mask. The gradient sits where it sits on the
// desktop tile (centre 50%/42%, radius 65% of the tile), with the tile laid
// over the foreground's scale.
func markBackgroundVector() string {
	s := markScale(brandmark.GeometryFor(512))
	tile := 512 * s
	cx := adaptiveViewport / 2
	cy := adaptiveViewport/2 + (0.42*512-256)*s
	return fmt.Sprintf(markHeader+`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="%s" android:centerY="%s"
                android:gradientRadius="%s">
                <item android:offset="0" android:color="%s" />
                <item android:offset="1" android:color="%s" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
`, "The OtherSync night tile, full-bleed.", n(cx), n(cy), n(0.65*tile), hexOf(nightCentre), hexOf(nightEdge))
}

// markForegroundVector is the ring, glow, glyph and centre point on
// transparency, the ring at ringSafeFill of the safe zone. mono is the themed
// icon layer: one flat colour (the platform tints it), no glow.
func markForegroundVector(mono bool) string {
	g := brandmark.GeometryFor(512)
	s := markScale(g)
	kind, what := "foreground", "The OtherSync mark: ring, glow, sync glyph and centre point."
	if mono {
		kind, what = "monochrome", "The OtherSync mark as one flat silhouette, for themed icons."
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, markHeader, what)
	b.WriteString(vectorOpen(108))
	fmt.Fprintf(&b, "    <!-- the %s layer, drawn in the mark's 512-unit design space -->\n", kind)
	b.WriteString(groupOpen(s, adaptiveViewport/2))
	colour := func(c color.RGBA) string {
		if mono {
			return "#FFFFFFFF"
		}
		return hexOf(c)
	}
	if !mono && g.GlowA > 0 {
		fmt.Fprintf(&b, "        <path android:strokeColor=%q android:strokeAlpha=%q android:strokeWidth=%q android:pathData=%q />\n",
			colour(brandmark.Teal), n(g.GlowA), n(g.GlowW), circlePath(g.RingR))
	}
	fmt.Fprintf(&b, "        <path android:strokeColor=%q android:strokeWidth=%q android:pathData=%q />\n",
		colour(brandmark.Teal), n(g.RingW), circlePath(g.RingR))
	writeGlyph(&b, g, colour(brandmark.Paper))
	if g.DotR > 0 {
		fmt.Fprintf(&b, "        <path android:fillColor=%q android:pathData=%q />\n",
			colour(brandmark.Glow), discPath(g.DotR))
	}
	b.WriteString("    </group>\n</vector>\n")
	return b.String()
}

// notificationVector is the notification small icon: Android keeps only its
// alpha, so it is the ring and sync glyph in white on transparency, 24dp,
// with the ring's outer edge on a 22dp circle. It uses the mark's heavy
// small-size geometry (the one the 24 px desktop icon uses): the status bar
// draws it about that size.
func notificationVector() string {
	g := brandmark.GeometryFor(24)
	const view, live = 24.0, 22.0
	s := live / 2 / (g.RingR + g.RingW/2)
	var b bytes.Buffer
	fmt.Fprintf(&b, markHeader, "Notification small icon: the OtherSync ring and sync glyph, white on transparency.")
	b.WriteString(vectorOpen(view))
	b.WriteString(groupOpen(s, view/2))
	fmt.Fprintf(&b, "        <path android:strokeColor=\"#FFFFFFFF\" android:strokeWidth=%q android:pathData=%q />\n",
		n(g.RingW), circlePath(g.RingR))
	writeGlyph(&b, g, "#FFFFFFFF")
	b.WriteString("    </group>\n</vector>\n")
	return b.String()
}

func vectorOpen(size float64) string {
	return fmt.Sprintf(`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="%[1]sdp"
    android:height="%[1]sdp"
    android:viewportWidth="%[1]s"
    android:viewportHeight="%[1]s">
`, n(size))
}

// groupOpen maps the design space (centre 256,256) onto a canvas centred on
// centre, at scale dp per unit. A group scales first and translates after.
func groupOpen(scale, centre float64) string {
	scale = math.Round(scale*1e4) / 1e4 // as written, so the centring is exact
	t := centre - 256*scale
	return fmt.Sprintf(`    <group
        android:scaleX="%[1]s" android:scaleY="%[1]s"
        android:translateX="%[2]s" android:translateY="%[2]s">
`, n4(scale), n4(t))
}

// writeGlyph draws the two sync arcs (round caps) and their arrowheads.
func writeGlyph(b *bytes.Buffer, g brandmark.Geometry, col string) {
	for _, a := range [][2]float64{{180 + g.GapDeg, 360 - g.GapDeg}, {g.GapDeg, 180 - g.GapDeg}} {
		fmt.Fprintf(b, "        <path android:strokeColor=%q android:strokeWidth=%q android:strokeLineCap=\"round\" android:pathData=%q />\n",
			col, n(g.ArcW), arcPath(g.ArcR, a[0], a[1]))
	}
	for _, t := range g.Arrows {
		d := fmt.Sprintf("M%s,%s L%s,%s L%s,%s Z", n(t[0][0]), n(t[0][1]), n(t[1][0]), n(t[1][1]), n(t[2][0]), n(t[2][1]))
		fmt.Fprintf(b, "        <path android:fillColor=%q android:strokeColor=%q android:strokeWidth=%q android:strokeLineJoin=\"round\" android:pathData=%q />\n",
			col, col, n(2*g.ArrowPad), d)
	}
}

// arcPath is a clockwise arc of radius r about (256,256) from a0 to a1
// degrees (0 = +x, y down).
func arcPath(r, a0, a1 float64) string {
	p := func(a float64) (float64, float64) {
		t := a * math.Pi / 180
		return 256 + r*math.Cos(t), 256 + r*math.Sin(t)
	}
	x0, y0 := p(a0)
	x1, y1 := p(a1)
	large := 0
	if a1-a0 > 180 {
		large = 1
	}
	return fmt.Sprintf("M%s,%s A%s,%s 0 %d,1 %s,%s", n(x0), n(y0), n(r), n(r), large, n(x1), n(y1))
}

// circlePath is a circle about (256,256) as two half arcs (a single
// 360-degree arc is degenerate).
func circlePath(r float64) string {
	return fmt.Sprintf("M%s,256 A%s,%s 0 1,1 %s,256 A%s,%s 0 1,1 %s,256 Z",
		n(256-r), n(r), n(r), n(256+r), n(r), n(r), n(256-r))
}

func discPath(r float64) string { return circlePath(r) }

// n4 keeps four decimals: a group's scale multiplies every coordinate.
func n4(v float64) string {
	s := fmt.Sprintf("%.4f", v)
	for len(s) > 1 && s[len(s)-1] == '0' {
		s = s[:len(s)-1]
	}
	if s[len(s)-1] == '.' {
		s = s[:len(s)-1]
	}
	return s
}
